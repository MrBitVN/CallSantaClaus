export function t(key: keyof typeof translations['en'], _lang?: any, params?: Record<string, string | number>): string {
  let str = translations['en'][key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return str;
}
